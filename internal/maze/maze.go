// dispatches on this.type. The default case there logs
// "Invalid maze type! Generating aborted." and returns null directly (not via
// throw, so the surrounding try/catch never sees it), runTrial treats that
// the same as any error from inside a run* method either way, so both flow
// through the same error return here. Neither this log nor the "Generating
// maze failed, reattempting..." console.error a few lines later in runTrial
// (mazeGenerator.js:1252) is ported: both are pure diagnostic output with no
// effect on what gets generated, same treatment as the profiler
// instrumentation in docs/found-bugs.md #2.
func (g *MazeGenerator) runByType() error {
	switch g.mazeType {
	case 0:
		return g.runNormal()
	case 1:
		return g.runNormal2()
	case 2:
		return g.run2Teams()
	case 4:
		return g.run4Teams()
	case 8:
		return g.run8Teams()
	case 9:
		return g.runMothership()
	case 10:
		return g.runBunker()
	case 11:
		return g.runFortress()
	case 12:
		return g.runCitadel()
	case 13:
		return g.runBlitz()
	case 14:
		return g.runSiegeOld()
	case 15:
		return g.runBooster()
	case 16:
		return g.runTrenches()
	case 17:
		return g.runLine()
	case 18:
		return g.runEye()
	case 19:
		return g.runAcropolis()
	case 20:
		return g.runYinYang()
	case 80:
		return g.run8TeamsLabyrinth()
	default:
		return fmt.Errorf("maze: invalid maze type %d", g.mazeType)
	}
}

// wraps the whole dispatch in try/catch and returns null on any exception.
// this checks the error instead of recovering a panic. nil here means "this
// trial didn't produce a usable maze, the caller should try again", covering
// three JS cases uniformly: an invalid type, a run* method's erosion running
// out of attempts, and an unwanted closed pocket.
func (g *MazeGenerator) runTrial() *mazeZone {
	if err := g.runByType(); err != nil {
		return nil
	}
	if g.isClosed() && !g.hasToBeClosed {
		return nil
	}
	return newMazeZone(g.maze)
}

// Smallest first. If all 10 failed, fall back to running up to 500 more and keep
// the first one that succeeds, no "smallest" comparison this time. Every
// successful trial's intoSquares() runs regardless of whether it ends up
// kept, exactly as the JS does. A fresh trial rebuilds the grid from
// scratch, so mutating a zone that then gets discarded has no effect on the
// next attempt.
//
// null, which its own callers would then crash on (`squares.forEach` on
// null, mazeGenerator.js consumers in game/gamemodes/scripts/*.js). Go has no
// implicit null to fall back on, so this returns an explicit error for that
// case instead. Strictly safer than the JS behaviour, and it does not change
// what a successful call produces.
func (g *MazeGenerator) PlaceMinimal() (Result, error) {
	var best []Square
	for i := 0; i < 10; i++ {
		trial := g.runTrial()
		if trial == nil {
			continue
		}
		squares := trial.intoSquares()
		if best == nil || len(squares) < len(best) {
			best = squares
		}
	}
	for i := 0; best == nil && i < 500; i++ {
		trial := g.runTrial()
		if trial == nil {
			continue
		}
		best = trial.intoSquares()
	}
	if best == nil {
		return Result{}, fmt.Errorf("maze: exhausted all attempts to generate type %d", g.mazeType)
	}
	return Result{Squares: best, Width: g.width, Height: g.height}, nil
}

// mazeZone mirrors the JS MazeZone class (mazeGenerator.js:1-142): the
// filled/wall part of a just-generated maze, decomposed into squares.
// nothing outside this file needs it either, runTrial builds one from
// this.maze and hands it straight to intoSquares(). Every one of its checks
// is a plain truthy test (never the strict `=== true` that matters inside
type mazeZone struct {
	array      [][]cellState // [x][y]
	offX, offY int
	length     int
}

// newMazeZone mirrors `new MazeZone(this.maze)` (mazeGenerator.js:1256): JS's
// default parameters give offset {0,0} and compute length as the total count
// of filled cells, the only constructor shape runTrial ever actually uses.
func newMazeZone(array [][]cellState) *mazeZone {
	length := 0
	for _, col := range array {
		for _, c := range col {
			if c != cellEmpty {
				length++
			}
		}
	}
	return &mazeZone{array: array, length: length}
}

// width/height mirror the width/height getters (mazeGenerator.js:7-12):
// unlike MazeGenerator's fields of the same name, these are recomputed from
// the current array every time, because normalize() actually resizes array
// (MazeGenerator's own width/height never need this, erosion only ever
// flips cells, never resizes the grid).
func (z *mazeZone) width() int { return len(z.array) }

func (z *mazeZone) height() int {
	if len(z.array) == 0 {
		return 0
	}
	return len(z.array[0])
}

// `row.every(r => !r)` (mazeGenerator.js:14,18).
func allEmpty(col []cellState) bool {
	for _, c := range col {
		if c != cellEmpty {
			return false
		}
	}
	return true
}

// normalize mirrors MazeZone.normalize (mazeGenerator.js:13-37): trim
// fully-empty leading/trailing columns (adjusting offX for the leading trim
// only, matching JS shift() bumping the offset but pop() not), then trim rows
// down to the [minY,maxY] band that actually holds a filled cell.
//

func (z *mazeZone) normalize() *mazeZone {
	for len(z.array) > 0 && allEmpty(z.array[0]) {
		z.offX++
		z.array = z.array[1:]
	}
	for len(z.array) > 0 && allEmpty(z.array[len(z.array)-1]) {
		z.array = z.array[:len(z.array)-1]
	}

	minY, maxY := 0, 0
	found := false
	for x := 0; x < z.width(); x++ {
		for y := 0; y < z.height(); y++ {
			if z.array[x][y] == cellEmpty {
				continue
			}
			if !found || y < minY {
				minY = y
			}
			if !found || y > maxY {
				maxY = y
			}
			found = true
		}
	}
	if !found {
		z.array = nil
		return z
	}
	z.offY += minY
	trimmed := make([][]cellState, len(z.array))
	for x, col := range z.array {
		trimmed[x] = col[minY : maxY+1]
	}
	z.array = trimmed
	return z
}

func (z *mazeZone) blocks() []Square {
	out := make([]Square, 0)
	for x := 0; x < z.width(); x++ {
		for y := 0; y < z.height(); y++ {
			if z.array[x][y] != cellEmpty {
				out = append(out, Square{X: x + z.offX, Y: y + z.offY, Size: 1})
			}
		}
	}
	return out
}

func (z *mazeZone) shaveSingles() (next *mazeZone, squares []Square, ok bool) {
	if z.length <= 3 {
		return nil, z.blocks(), true
	}

	width, height := z.width(), z.height()
	output := make([]Square, 0)
	shaved := false
	for {
		shaveable := false
		for x := 0; x < width; x++ {
			for y := 0; y < height; y++ {
				if z.array[x][y] == cellEmpty {
					continue
				}
				left := x > 0 && z.array[x-1][y] != cellEmpty
				right := x+1 < width && z.array[x+1][y] != cellEmpty
				top := y > 0 && z.array[x][y-1] != cellEmpty
				bottom := y+1 < height && z.array[x][y+1] != cellEmpty
				if (!left && !right) || (!top && !bottom) {
					z.array[x][y] = cellEmpty
					output = append(output, Square{X: x + z.offX, Y: y + z.offY, Size: 1})
					shaveable = true
				}
			}
		}
		shaved = shaved || shaveable
		if !shaveable {
			break
		}
	}
	z.length -= len(output)
	if shaved {
		return z.normalize(), output, true
	}
	return nil, nil, false
}

// takeBiggestSquare mirrors MazeZone.takeBiggestSquare (mazeGenerator.js:82-115):
// find the filled cell that roots the largest all-filled axis-aligned square
// (growing it one ring at a time until a new border cell comes up empty),
// x-major scan order, the JS uses a strict `size > maxSize`, not `>=`, so
// this must too.
//
// found is false only when the grid has no filled cell at all, which never
// shaveSingles reported ok=false, and that requires z.length > 3. Guarded
// way JS's `best` starting at null and staying null would.
func (z *mazeZone) takeBiggestSquare() (Square, bool) {
	width, height := z.width(), z.height()
	bestX, bestY, maxSize := 0, 0, 0
	found := false

	for x := 0; x < width; x++ {
		for y := 0; y < height; y++ {
			if z.array[x][y] == cellEmpty {
				continue
			}
			size := 1
		grow:
			for x+size < width && y+size < height {
				for i := 0; i <= size; i++ {
					if z.array[x+size][y+i] == cellEmpty || z.array[x+i][y+size] == cellEmpty {
						break grow
					}
				}
				size++
			}
			if size > maxSize {
				maxSize = size
				bestX, bestY = x, y
				found = true
			}
		}
	}
	if !found {
		return Square{}, false
	}

	z.length -= maxSize * maxSize
	for x := 0; x < maxSize; x++ {
		for y := 0; y < maxSize; y++ {
			z.array[bestX+x][bestY+y] = cellEmpty
		}
	}
	square := Square{X: bestX + z.offX, Y: bestY + z.offY, Size: maxSize}
	if bestX == 0 || bestX+maxSize == width || bestY == 0 || bestY+maxSize == height {
		z.normalize()
	}
	return square, true
}

// shave mirrors MazeZone.shave (mazeGenerator.js:116-123): normalize, then
// try shaveSingles. If it had nothing to do, fall back to taking the single
// biggest square instead.
func (z *mazeZone) shave() (*mazeZone, []Square) {
	z.normalize()
	if next, squares, ok := z.shaveSingles(); ok {
		return next, squares
	}
	square, found := z.takeBiggestSquare()
	if !found {
		// Unreachable in practice, see takeBiggestSquare's doc comment.
		// but this is the only sane thing to return if it ever were.
		return nil, nil
	}
	if z.width() == 0 || z.height() == 0 {
		return nil, []Square{square}
	}
	return z, []Square{square}
}

// intoSquares mirrors MazeZone.intoSquares (mazeGenerator.js:124-133):
func (z *mazeZone) intoSquares() []Square {
	squares := make([]Square, 0)
	current := z
	for current != nil {
		next, produced := z.shave()
		current = next
		squares = append(squares, produced...)
	}
	return squares
}
